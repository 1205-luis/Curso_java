public class TiposDeDatos {
    public static void main(String[] args) {

        /*
        Tipos de datos primitivos 
        siempre que se quiera usar como tipo de dato se hace con la primer en minus, si se va ausar como class se hace con la primera en mayus.
        */
        

        // Estos son enteros normales 
        int myInt = 20;
        System.out.println(myInt);

        // Estos son los decimales 
        double myDouble = 1.70;
        System.out.println(myDouble);

        //Este es para crear un caracter de unico valor
        char myChar = 'a';
        System.out.println(myChar);

        //Este es True o False, y se utiliza con la primera en minus
        boolean myBoolean = true;
        myBoolean = false;
        System.out.println(myBoolean);
        
    }
    
}
